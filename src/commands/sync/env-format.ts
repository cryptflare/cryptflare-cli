/** Env-file parse/format helpers shared by `cf pull`, `cf push`, `cf diff` and `cf daemon`. */

import chalk from 'chalk'
import * as output from '@/lib/output'
import { parseEnvContent, renderEnvFile, toValueMap } from '@/lib/env-file'

export const parseEnvFile = (content: string): Map<string, string> =>
  toValueMap(parseEnvContent(content))
export const formatEnvFile = (secrets: Map<string, string>): string =>
  renderEnvFile(secrets, `# Generated by CryptFlare CLI\n# ${new Date().toISOString()}`)

/**
 * Warns when a pulled value contains a newline.
 *
 * The writer encodes it as `KEY="line1\nline2"`, which this parser and dotenv
 * both decode back to a real newline. A POSIX shell does not: `\n` inside
 * double quotes is a literal backslash and an `n`, so `set -a; . .env` yields
 * the wrong value with no indication anything was lost. A real newline in
 * single quotes would source correctly but is exactly the multi-line form the
 * parser refuses to rewrite in place, so the encoding stays and the caller is
 * told instead. `cf env -f shell` emits a shell-correct form for these.
 */
export function findNewlineValues(values: Map<string, string>): string[] {
  return [...values.entries()].filter(([, v]) => v.includes('\n')).map(([k]) => k)
}

export function warnAboutNewlineValues(values: Map<string, string>): void {
  const keys = findNewlineValues(values)
  if (keys.length === 0) return
  output.warn(
    `${keys.length} value(s) contain newlines and are written escaped: ${keys.join(', ')}.`,
  )
  output.printError(
    chalk.dim(
      `  Readable by dotenv and by \`cf\`, but sourcing the file in a shell yields a literal \\n.\n` +
        `  For shell use: ${chalk.cyan('eval "$(cf env -f shell)"')}`,
    ),
  )
}
